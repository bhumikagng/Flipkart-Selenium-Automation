package com.flipkart.pages;

import java.util.List;

import org.openqa.selenium.By;
import org.openqa.selenium.WebElement;
import org.openqa.selenium.support.FindBy;
import org.openqa.selenium.support.PageFactory;

import com.flipkart.reusable.SeleniumReusable;

/**
 * SearchPage
 * <p>
 * Elements and actions for the Flipkart home page: the top navigation bar
 * (used for hover-based category navigation), the login interstitial popup,
 * the search bar, and the resulting search listing page (product titles and
 * prices).
 * <p>
 * NOTE ON LOCATORS: Flipkart's CSS class names (e.g. {@code _4rR01T},
 * {@code _30jeq3}) are generated by their front-end build tooling and change
 * on redeploys, so they are used here only as a fallback alongside more
 * stable attributes/structure. Re-verify every locator in this class against
 * the live DOM (browser DevTools -&gt; Inspect) before relying on it; a UI
 * this dynamic will drift out from under any hard-coded locator sooner or
 * later, and re-verifying is a normal part of maintaining this suite.
 */
public class SearchPage extends SeleniumReusable {

    public SearchPage() {
        PageFactory.initElements(driver, this);
    }

    @FindBy(name = "q")
    private WebElement searchBox;

    private final By searchBoxLocator = By.name("q");
    private final By loginPopupCloseLocator = By.xpath("//button[text()='✕']");
    private final By productTitleLocator =
            By.xpath("//div[contains(@class,'_4rR01T') or contains(@class,'IRpwTa') or contains(@class,'_2WkVRV') or contains(@class,'wjcEIp')]");
    private final By productPriceLocator =
            By.xpath("//div[contains(@class,'_30jeq3') or contains(@class,'Nx9bqj')]");

    // ---------------------------------------------------------------
    // Login popup
    // ---------------------------------------------------------------

    /**
     * Closes the "Login" interstitial if Flipkart shows it for this session.
     * The popup is session/region/first-visit dependent, so this checks for
     * it rather than assuming it is (or isn't) there.
     */
    public void closeLoginPopupIfPresent() {
        if (isDisplayed(loginPopupCloseLocator, 5)) {
            click(loginPopupCloseLocator);
            log.info("Closed login popup");
        } else {
            log.info("Login popup was not shown for this session");
        }
    }

    // ---------------------------------------------------------------
    // Search
    // ---------------------------------------------------------------

    public void searchFor(String term) {
        sendKeys(searchBox, term);
        searchBox.submit();
        log.info("Searched for term: {}", term);
    }

    public boolean isSearchResultsPageDisplayed() {
        return isDisplayed(productTitleLocator, 15);
    }

    public List<String> getAllProductTitles() {
        return multipleGetText(productTitleLocator);
    }

    public List<String> getAllProductPrices() {
        return multipleGetText(productPriceLocator);
    }

    // ---------------------------------------------------------------
    // Hover navigation (top nav bar), e.g. Fashion -> Kids -> Girls Dress,
    // or Plus Zone -> Home Furniture -> Wall Lamp
    // ---------------------------------------------------------------

    /**
     * Hovers over a top-level nav item, then a sub-category revealed by that
     * hover, then clicks a final link revealed by the second hover. Works
     * for any 3-level hover path in Flipkart's top navigation.
     */
    public void hoverAndClickCategory(String topLevel, String subLevel, String finalLink) {
        By topLevelLocator = By.xpath(
                "//a[normalize-space(text())='" + topLevel + "'] | //div[normalize-space(text())='" + topLevel + "']");
        By subLevelLocator = By.xpath(
                "//div[normalize-space(text())='" + subLevel + "'] | //a[normalize-space(text())='" + subLevel + "']");
        By finalLinkLocator = By.xpath(
                "//a[normalize-space(text())='" + finalLink + "'] | //div[normalize-space(text())='" + finalLink + "']");

        mouseHover(topLevelLocator);
        mouseHover(subLevelLocator);
        click(finalLinkLocator);
        log.info("Navigated via hover: {} -> {} -> {}", topLevel, subLevel, finalLink);
    }
}
